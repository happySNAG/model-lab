describe('grading one attempt', () => {
  const outcome = (id: string, metric: string, held: boolean, extra: Partial<{ visibility: 'stated' | 'heldOut'; shortcutProbe: boolean }> = {}) => ({
    id, metric, held, detail: `${id} ${held ? 'held' : 'did not hold'}`,
    visibility: extra.visibility ?? ('heldOut' as const), shortcutProbe: extra.shortcutProbe ?? false,
  });

  const everyStructuralMetricHolding = metricsForDimension('multiFileEditing')
    .filter((spec) => spec.tier === 'structural' && spec.id !== 'retryBehaviour')
    .map((spec) => outcome(`ok-${spec.id}`, spec.id, true));

  it('never awards full credit while the executed tier is unmeasured', () => {
    const grade = gradeTask('multiFileEditing', everyStructuralMetricHolding);
    expect(grade.structuralCredit).toBe('full');
    expect(grade.executedCredit).toBe('notMeasured');
    expect(grade.credit).toBe('partial');
    expect(grade.creditReason).toContain('newTestsPass');
    expect(grade.creditReason).toContain('no OS sandbox');
  });

  it('reports an executed metric as not measured with a reason, never as a zero', () => {
    const grade = gradeTask('multiFileEditing', everyStructuralMetricHolding);
    for (const id of ['newTestsPass', 'existingTestsPass', 'buildSucceeds'] as const) {
      const result = grade.metrics.find((metric) => metric.id === id)!;
      expect(result.status).toBe('notMeasured');
      expect(result.valueMilli).toEqual({ unavailableReason: EXECUTED_TIER_NOT_MEASURED_REASON });
      expect('measured' in result.valueMilli).toBe(false);
    }
  });

  it('fails the gate when a required file was omitted, however good the rest is', () => {
    const outcomes = everyStructuralMetricHolding.map((entry) =>
      entry.metric === 'requiredFilesPresent' ? { ...entry, held: false } : entry);
    const grade = gradeTask('multiFileEditing', outcomes);
    expect(grade.structuralCredit).toBe('partial');
    expect(grade.credit).toBe('partial');
    expect(grade.metrics.find((metric) => metric.id === 'requiredFilesPresent')!.status).toBe('fail');
    expect(grade.creditReason).toContain('requiredFilesPresent');
  });

  it('gives a metric with no assertion notApplicable rather than a free pass', () => {
    const grade = gradeTask('multiFileEditing', [outcome('only', 'correctFilesEdited', true)]);
    const untested = grade.metrics.find((metric) => metric.id === 'implementationCorrectness')!;
    expect(untested.status).toBe('notApplicable');
    expect(untested.valueMilli).toEqual({ unavailableReason: 'this task declares no assertion for this metric' });
    expect(grade.structuralCredit).toBe('full');
  });

  it('reports none when no gating structural metric was decided at all', () => {
    const grade = gradeTask('multiFileEditing', []);
    expect(grade.structuralCredit).toBe('none');
    expect(grade.credit).toBe('none');
  });

  it('computes a metric rate over its own assertions only', () => {
    const grade = gradeTask('repositoryUnderstanding', [
      outcome('a', 'answerAccuracy', true),
      outcome('b', 'answerAccuracy', false),
      outcome('c', 'omissionAvoidance', true),
    ]);
    const accuracy = grade.metrics.find((metric) => metric.id === 'answerAccuracy')!;
    expect(accuracy.valueMilli).toEqual({ measured: 500 });
    expect(accuracy.status).toBe('fail');
    expect(accuracy.assertionIDs).toEqual(['a', 'b']);
    expect(accuracy.detail).toContain('b did not hold');
    expect(grade.metrics.find((metric) => metric.id === 'omissionAvoidance')!.valueMilli).toEqual({ measured: 1_000 });
  });

  it('separates a suspected shortcut from a lost point', () => {
    const clean = gradeTask('multiFileEditing', everyStructuralMetricHolding);
    expect(clean.shortcutSuspected).toBe(false);
    expect(clean.shortcutReasons).toEqual([]);

    const probed = gradeTask('multiFileEditing', [
      ...everyStructuralMetricHolding,
      outcome('hardcoded', 'implementationCorrectness', false, { shortcutProbe: true }),
    ]);
    expect(probed.shortcutSuspected).toBe(true);
    expect(probed.shortcutReasons[0]).toContain('hardcoded');
  });

  it('reports the held-out rate over held-out assertions only', () => {
    const grade = gradeTask('repositoryUnderstanding', [
      outcome('stated-pass', 'answerAccuracy', true, { visibility: 'stated' }),
      outcome('held-pass', 'answerAccuracy', true, { visibility: 'heldOut' }),
      outcome('held-fail', 'answerAccuracy', false, { visibility: 'heldOut' }),
    ]);
    expect(grade.heldOutPassRateMilli).toEqual({ measured: 500 });

    const noneHeldOut = gradeTask('repositoryUnderstanding', [outcome('s', 'answerAccuracy', true, { visibility: 'stated' })]);
    expect(noneHeldOut.heldOutPassRateMilli).toEqual({ unavailableReason: 'this task declares no held-out assertion' });
  });

  it('records retry behaviour when the runner supplied it, and not measured when it did not', () => {
    expect(gradeTask('multiFileEditing', everyStructuralMetricHolding).metrics
      .find((metric) => metric.id === 'retryBehaviour')!.status).toBe('notMeasured');
    expect(gradeTask('multiFileEditing', everyStructuralMetricHolding, { retryDetail: 'one retry, converged' }).metrics
      .find((metric) => metric.id === 'retryBehaviour')!.detail).toBe('one retry, converged');
  });

  it('never reports a metric from the other dimension', () => {
    const grade = gradeTask('repositoryUnderstanding', [outcome('a', 'answerAccuracy', true)]);
    expect(grade.metrics.map((metric) => metric.id)).toEqual(metricsForDimension('repositoryUnderstanding').map((spec) => spec.id));
    expect(grade.metrics.some((metric) => metric.id === 'churnRestraint')).toBe(false);
  });
});

describe('development task and suite validation', () => {
  const assertion = (fields: Partial<DevelopmentAssertion> = {}): DevelopmentAssertion => ({
    id: 'a1', purpose: 'probe', metric: 'implementationCorrectness', visibility: 'heldOut',
    predicate: { kind: 'containsPhrase', path: 'src/util/money.js', phrase: 'Math.round' },
    ...fields,
  });

  const editTask = (fields: Partial<DevelopmentTask> = {}): DevelopmentTask => makeDevelopmentTask({
    id: 'task.dev.edit.probe',
    suiteID: 'suite.cernum.development.multi-file-edit',
    suiteVersion: '1',
    dimension: 'multiFileEditing',
    kind: 'repositoryEdit',
    capabilityUnderTest: 'probe',
    fixtureRepoID: ledgerlite.id,
    fixtureRepoVersion: ledgerlite.version,
    fixtureRepoDigest: LEDGERLITE_DIGEST,
    prompt: { system: 'system', user: 'user' },
    requiredPaths: ['src/util/money.js', 'src/core/stages/round.js', 'test/cases/rounding.cases.json'],
    permittedPaths: ['CHANGELOG.md'],
    assertions: [assertion()],
    executionBudgetMilliseconds: 600_000,
    plannedRepetitions: 1,
    scoringContractID: DEVELOPMENT_SCORING_CONTRACT_ID,
    scoringContractVersion: DEVELOPMENT_SCORING_CONTRACT_VERSION,
    provenance: 'probe',
    tags: ['probe'],
    ...fields,
  });

  const suiteOf = (task: DevelopmentTask): DevelopmentSuite =>
    makeDevelopmentSuite(task.suiteID, task.suiteVersion, 'probe suite', task.dimension, [task]);

  const validate = (task: DevelopmentTask) => validateDevelopmentSuite(suiteOf(task), [ledgerlite]);

  it('accepts a well-formed multi-file-editing task', () => {
    expect(() => validate(editTask())).not.toThrow();
  });

  it('refuses a task a one-file patch could satisfy', () => {
    expect(MINIMUM_REQUIRED_FILES_FOR_MULTI_FILE_EDIT).toBe(3);
    expect(() => validate(editTask({ requiredPaths: ['src/util/money.js'] }))).toThrow(/does not measure this dimension/);
    expect(() => validate(editTask({ requiredPaths: ['src/util/money.js', 'test/cases/rounding.cases.json'] }))).toThrow(DevelopmentValidationFailure);
  });

  it('refuses a task whose every check is something the prompt already states', () => {
    expect(() => validate(editTask({ assertions: [assertion({ visibility: 'stated' })] })))
      .toThrow(/transcription rather than understanding/);
  });

  it('refuses a structural assertion attached to an executed metric', () => {
    expect(() => validate(editTask({ assertions: [assertion({ metric: 'newTestsPass' })] })))
      .toThrow(/masquerade as a test run/);
  });

  it('refuses a metric that belongs to the other dimension, and an unknown metric', () => {
    expect(() => validate(editTask({ assertions: [assertion({ metric: 'answerAccuracy' })] }))).toThrow(/belongs to repositoryUnderstanding/);
    expect(() => validate(editTask({ assertions: [assertion({ metric: 'conversation' })] }))).toThrow(/unknown metric/);
  });

  it('refuses a task sealed against a fixture digest the fixture no longer has', () => {
    expect(() => validate(editTask({ fixtureRepoDigest: 'mldr1:0000000000000000' })))
      .toThrow(/the fixture changed under a task that did not/);
  });

  it('refuses a task naming a fixture repository that is not registered', () => {
    expect(() => validate(editTask({ fixtureRepoID: 'fixture.repo.nope' }))).toThrow(/not registered/);
  });

  it('refuses an assertion naming a path that is in neither the fixture nor the task scope', () => {
    expect(() => validate(editTask({ assertions: [assertion({ predicate: { kind: 'fileExists', path: 'src/invented.js' } })] })))
      .toThrow(/neither in fixture repository/);
    // A required path that does not yet exist IS in scope: that is how "add this file" is expressed.
    expect(() => validate(editTask({
      requiredPaths: ['src/util/money.js', 'src/core/stages/round.js', 'test/cases/refunds.cases.json'],
      assertions: [assertion({ predicate: { kind: 'fileExists', path: 'test/cases/refunds.cases.json' } })],
    }))).not.toThrow();
  });

  it('refuses a scoring contract this engine does not register', () => {
    expect(() => validate(editTask({ scoringContractVersion: '2' }))).toThrow(/registers only/);
    expect(() => validate(editTask({ scoringContractID: 'contract.other' }))).toThrow(/registers only/);
  });

  it('refuses an empty prompt, a zero budget and zero repetitions', () => {
    expect(() => validate(editTask({ prompt: { system: '', user: 'u' } }))).toThrow(/empty prompt/);
    expect(() => validate(editTask({ executionBudgetMilliseconds: 0 }))).toThrow(/positive execution budget/);
    expect(() => validate(editTask({ plannedRepetitions: 0 }))).toThrow(/zero repetitions/);
  });

  it('holds a read-only task to exactly the reserved answer path', () => {
    const question = editTask({
      id: 'task.dev.question.probe', kind: 'repositoryQuestion', dimension: 'repositoryUnderstanding',
      suiteID: 'suite.cernum.development.repo-understanding',
      requiredPaths: [DEVELOPMENT_ANSWER_PATH], permittedPaths: [],
      assertions: [assertion({ metric: 'answerAccuracy', predicate: { kind: 'jsonHasPointer', path: DEVELOPMENT_ANSWER_PATH, pointer: '/file' } })],
    });
    expect(() => validate(question)).not.toThrow();
    expect(() => validate({ ...question, requiredPaths: ['src/index.js'] })).toThrow(/must require exactly/);
    expect(() => validate({ ...editTask(), requiredPaths: [...editTask().requiredPaths, DEVELOPMENT_ANSWER_PATH] }))
      .toThrow(/judged by what it did to the repository/);
  });

  it('refuses a fixture that already occupies the reserved answer path', () => {
    const colliding = makeFixtureRepo({
      ...ledgerlite,
      files: [...ledgerlite.files, { path: DEVELOPMENT_ANSWER_PATH, role: 'doc', contents: '{}' }],
    });
    const task = editTask({ fixtureRepoDigest: fixtureRepoDigest(colliding) });
    expect(() => validateDevelopmentSuite(suiteOf(task), [colliding])).toThrow(/reserved for a task/);
  });

  it('refuses duplicate task ids, a task outside its suite, and a dimension mismatch', () => {
    const task = editTask();
    expect(() => validateDevelopmentSuite({ ...suiteOf(task), tasks: [task, task] }, [ledgerlite])).toThrow(/duplicate development task id/);
    expect(() => validateDevelopmentSuite({ ...suiteOf(task), id: 'suite.other' }, [ledgerlite])).toThrow(/declares suite/);
    expect(() => validateDevelopmentSuite({ ...suiteOf(task), version: '9' }, [ledgerlite])).toThrow(/declares version/);
    expect(() => validateDevelopmentSuite({ ...suiteOf(task), dimension: 'repositoryUnderstanding' }, [ledgerlite]))
      .toThrow(/a rate nobody can read/);
    expect(() => validateDevelopmentSuite({ ...suiteOf(task), tasks: [] }, [ledgerlite])).toThrow(/declares no tasks/);
    expect(() => validateDevelopmentSuite(suiteOf({ ...task, assertions: [] }), [ledgerlite])).toThrow(/nothing would judge it/);
    expect(() => validateDevelopmentSuite(suiteOf({ ...task, assertions: [assertion(), assertion({ visibility: 'stated' })] }), [ledgerlite]))
      .toThrow(/twice/);
  });

  it('seals a task, and changes its identity when the contract version changes', () => {
    const task = editTask();
    expect(developmentTaskDigest(task)).toBe(developmentTaskDigest(makeDevelopmentTask({ ...task })));
    expect(developmentTaskDigest(task)).not.toBe(developmentTaskDigest({ ...task, prompt: { system: 's', user: 'different' } }));

    const key = developmentComparabilityKey(task);
    expect(key.startsWith('mldk1:')).toBe(true);
    expect(developmentComparabilityKey({ ...task, scoringContractVersion: '2' })).not.toBe(key);
    expect(developmentComparabilityKey({ ...task, fixtureRepoDigest: 'mldr1:other' })).not.toBe(key);

    const suite = suiteOf(task);
    expect(developmentSuiteDigest(suite).startsWith('mldsu1:')).toBe(true);
    expect(developmentSuiteDigest(suite)).not.toBe(developmentSuiteDigest({ ...suite, version: '2' }));
  });

  it('normalizes a task so two spellings of the same task seal alike', () => {
    const one = editTask({ tags: ['b', 'a', 'b'], permittedPaths: ['z', 'a', 'z'] });
    const two = editTask({ tags: ['a', 'b'], permittedPaths: ['a', 'z'] });
    expect(one.tags).toEqual(['a', 'b']);
    expect(one.permittedPaths).toEqual(['a', 'z']);
    expect(developmentTaskDigest(one)).toBe(developmentTaskDigest(two));
  });
});

