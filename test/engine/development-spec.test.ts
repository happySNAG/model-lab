// The fixture as sealed at authoring time. A change to any byte of `ledgerlite` changes this, and a
// change to the fixture under a task that did not change is exactly what the drift check catches.
const LEDGERLITE_DIGEST = 'mldr1:69aebcb7bc9d6d03';
const CONTRACT_DIGEST = 'mldc1:cafc30af44a5f467';

describe('the ledgerlite fixture repository', () => {
  it('validates, and seals to the digest the tasks are written against', () => {
    expect(() => validateFixtureRepo(ledgerlite)).not.toThrow();
    expect(fixtureRepoDigest(ledgerlite)).toBe(LEDGERLITE_DIGEST);
    expect(developmentFixtureRepos).toContain(ledgerlite);
  });

  it('carries the three traps the repository-understanding suite depends on', () => {
    const byPath = new Map(ledgerlite.files.map((file) => [file.path, file]));

    // Trap 1: the public surface forwards. A shallow search for `createCharge` finds the facade.
    expect(byPath.get('src/api/charges.js')!.contents).toContain('runChargePipeline');
    expect(byPath.get('src/core/charge-pipeline.js')!.contents).toContain('function runChargePipeline');

    // Trap 2: the generated module declares its source, and the fixture says so structurally.
    const generated = byPath.get('src/schema/generated/charge-fields.js')!;
    expect(generated.role).toBe('generated');
    expect(generated.generatedFrom).toBe('src/schema/charge.schema.json');
    expect(generated.contents).toContain('DO NOT EDIT THIS FILE BY HAND');

    // Trap 3: rounding goes through Math.round and no golden case is negative.
    expect(byPath.get('src/util/money.js')!.contents).toContain('Math.round');
    const table = JSON.parse(byPath.get('test/cases/rounding.cases.json')!.contents) as { cases: { amount: number }[] };
    expect(table.cases.every((entry) => entry.amount > 0)).toBe(true);
  });

  it('is internally consistent: the generated field list agrees with the schema it names', () => {
    // The invariant the multi-file-edit suite is built on. A candidate that adds a field to the
    // schema and does not regenerate the derived module breaks exactly this, and it is checkable
    // from the bytes alone — no generator has to be run to see the disagreement.
    const byPath = new Map(ledgerlite.files.map((file) => [file.path, file.contents]));
    const schema = JSON.parse(byPath.get('src/schema/charge.schema.json')!) as {
      fields: { name: string; required: boolean }[];
    };
    const generated = byPath.get('src/schema/generated/charge-fields.js')!;
    const readArray = (name: string): string[] =>
      JSON.parse(new RegExp(`const ${name} = (\\[[^\\]]*\\]);`).exec(generated)![1]) as string[];

    expect(readArray('CHARGE_FIELDS')).toEqual(schema.fields.map((field) => field.name));
    expect(readArray('REQUIRED_CHARGE_FIELDS')).toEqual(schema.fields.filter((field) => field.required).map((field) => field.name));
  });

  it('declares every file with a role, and only a generated file names a producer', () => {
    for (const file of ledgerlite.files) {
      expect(file.contents.length).toBeGreaterThan(0);
      if (file.role !== 'generated') expect(file.generatedFrom).toBeUndefined();
    }
    expect(ledgerlite.files.filter((file) => file.role === 'generated')).toHaveLength(1);
    expect(ledgerlite.files.some((file) => file.role === 'test')).toBe(true);
    expect(ledgerlite.files.some((file) => file.role === 'tooling')).toBe(true);
  });
});

describe('fixture repository validation is fail-closed', () => {
  const base = (files: FixtureRepo['files']): FixtureRepo =>
    makeFixtureRepo({ id: 'fixture.repo.probe', version: '1', title: 'probe', summary: 'probe', files });

  const ok = { path: 'src/a.js', role: 'source' as const, contents: 'x' };

  it('refuses a path that is not a plain POSIX-relative path', () => {
    for (const path of ['/etc/passwd', '../escape.js', './a.js', 'a\\b.js', 'a//b.js']) {
      expect(() => validateFixtureRepo(base([{ ...ok, path }])), path).toThrow(FixtureRepoValidationFailure);
    }
  });

  it('refuses a duplicate path, an empty file, and a repository with no source', () => {
    expect(() => validateFixtureRepo({ ...base([ok]), files: [ok, ok] })).toThrow(/twice/);
    expect(() => validateFixtureRepo(base([{ ...ok, contents: '' }]))).toThrow(/no contents/);
    expect(() => validateFixtureRepo(base([{ path: 'README.md', role: 'doc', contents: 'x' }]))).toThrow(/no source file/);
  });

  it('refuses a generated file with no source, a missing source, or a self-reference', () => {
    expect(() => validateFixtureRepo(base([ok, { path: 'g.js', role: 'generated', contents: 'x' }]))).toThrow(/names no source/);
    expect(() => validateFixtureRepo(base([ok, { path: 'g.js', role: 'generated', generatedFrom: 'nope.json', contents: 'x' }]))).toThrow(/does not contain/);
    expect(() => validateFixtureRepo(base([ok, { path: 'g.js', role: 'generated', generatedFrom: 'g.js', contents: 'x' }]))).toThrow(/generated from itself/);
  });

  it('refuses a non-generated file that names a producer', () => {
    expect(() => validateFixtureRepo(base([{ ...ok, generatedFrom: 'src/a.js' }]))).toThrow(/only a generated file/);
  });

  it('refuses an empty repository and one with no id or version', () => {
    expect(() => validateFixtureRepo(base([]))).toThrow(/no files/);
    expect(() => validateFixtureRepo({ ...base([ok]), id: '' })).toThrow(/no id/);
    expect(() => validateFixtureRepo({ ...base([ok]), version: '' })).toThrow(/no version/);
  });
});

describe('snapshots and differences', () => {
  const baseline = snapshotOf(ledgerlite);

  it('seals a snapshot and orders its paths deterministically', () => {
    expect(snapshotDigest(baseline)).toBe('mldsnap1:aa43e94dc603411');
    expect(snapshotPaths(baseline)).toEqual([...snapshotPaths(baseline)].sort());
    expect(snapshotPaths(baseline)).toHaveLength(17);
  });

  it('classifies every path as added, removed, modified or unchanged, and nothing twice', () => {
    const result = new Map(baseline);
    result.set('src/util/money.js', 'changed');
    result.set('src/util/rounding.js', 'new');
    result.delete('CHANGELOG.md');

    const difference = diffSnapshots(baseline, result);
    expect(difference.added).toEqual(['src/util/rounding.js']);
    expect(difference.removed).toEqual(['CHANGELOG.md']);
    expect(difference.modified).toEqual(['src/util/money.js']);
    expect(difference.unchanged).toHaveLength(15);
    expect(touchedPaths(difference)).toEqual(['CHANGELOG.md', 'src/util/money.js', 'src/util/rounding.js']);

    const all = [...difference.added, ...difference.removed, ...difference.modified, ...difference.unchanged];
    expect(new Set(all).size).toBe(all.length);
  });

  it('reports an untouched repository as entirely unchanged', () => {
    const difference = diffSnapshots(baseline, new Map(baseline));
    expect(touchedPaths(difference)).toEqual([]);
    expect(difference.unchanged).toHaveLength(17);
  });
});

describe('the assertion predicate language', () => {
  const baseline: AssertionContext['baseline'] = new Map([
    ['a.json', '{"fields":["amount","region"],"nested":{"deep":[1,2]}}'],
    ['b.js', 'function total() { return 1; }\n'],
    ['c.md', 'untouched\n'],
  ]);
  const context = (result: Map<string, string>): AssertionContext => ({ baseline, result });
  const unchanged = () => context(new Map(baseline));

  it('decides existence and absence', () => {
    expect(evaluatePredicate({ kind: 'fileExists', path: 'b.js' }, unchanged()).held).toBe(true);
    expect(evaluatePredicate({ kind: 'fileExists', path: 'nope' }, unchanged()).held).toBe(false);
    expect(evaluatePredicate({ kind: 'fileAbsent', path: 'nope' }, unchanged()).held).toBe(true);
    expect(evaluatePredicate({ kind: 'fileAbsent', path: 'b.js' }, unchanged()).held).toBe(false);
  });

  it('decides changed and unchanged against the baseline, and calls a deletion a failure to preserve', () => {
    const edited = new Map(baseline);
    edited.set('b.js', 'function total() { return 2; }\n');
    expect(evaluatePredicate({ kind: 'changedFromBaseline', path: 'b.js' }, context(edited)).held).toBe(true);
    expect(evaluatePredicate({ kind: 'unchangedFromBaseline', path: 'b.js' }, context(edited)).held).toBe(false);
    expect(evaluatePredicate({ kind: 'unchangedFromBaseline', path: 'c.md' }, context(edited)).held).toBe(true);

    const deleted = new Map(baseline);
    deleted.delete('c.md');
    const verdict = evaluatePredicate({ kind: 'unchangedFromBaseline', path: 'c.md' }, context(deleted));
    expect(verdict.held).toBe(false);
    expect(verdict.detail).toMatch(/deleted/);

    // An added file counts as changed; a file that never arrived does not.
    const added = new Map(baseline);
    added.set('new.js', 'x');
    expect(evaluatePredicate({ kind: 'changedFromBaseline', path: 'new.js' }, context(added)).held).toBe(true);
    expect(evaluatePredicate({ kind: 'changedFromBaseline', path: 'new.js' }, unchanged()).held).toBe(false);
  });

  it('fences scope with onlyTheseTouched, and names every path that strayed', () => {
    const strayed = new Map(baseline);
    strayed.set('b.js', 'edited');
    strayed.set('c.md', 'also edited');
    const verdict = evaluatePredicate({ kind: 'onlyTheseTouched', paths: ['b.js'] }, context(strayed));
    expect(verdict.held).toBe(false);
    expect(verdict.detail).toContain('c.md');
    expect(evaluatePredicate({ kind: 'onlyTheseTouched', paths: ['b.js', 'c.md'] }, context(strayed)).held).toBe(true);
  });

  it('matches phrases on code terms rather than on prose-folded text', () => {
    expect(normalizeCode('A  \t B')).toBe('a b');
    expect(codeContainsPhrase('charge.currency = x', 'charge.currency')).toBe(true);
    // The prose normalizer folds punctuation; this one must not, or an assertion naming an
    // expression would match text that does not contain that expression.
    expect(codeContainsPhrase('charge_currency = x', 'charge.currency')).toBe(false);
    expect(codeContainsPhrase('CHARGE.Currency', 'charge.currency')).toBe(true);
  });

  it('decides containsPhrase, lacksPhrase, matches and occursAtLeast', () => {
    const result = unchanged();
    expect(evaluatePredicate({ kind: 'containsPhrase', path: 'b.js', phrase: 'function total' }, result).held).toBe(true);
    expect(evaluatePredicate({ kind: 'lacksPhrase', path: 'b.js', phrase: 'TODO' }, result).held).toBe(true);
    expect(evaluatePredicate({ kind: 'lacksPhrase', path: 'b.js', phrase: 'return 1' }, result).held).toBe(false);
    expect(evaluatePredicate({ kind: 'matches', path: 'b.js', pattern: 'function\\s+total' }, result).held).toBe(true);
    expect(evaluatePredicate({ kind: 'occursAtLeast', path: 'b.js', pattern: 'return', minimum: 1 }, result).held).toBe(true);
    expect(evaluatePredicate({ kind: 'occursAtLeast', path: 'b.js', pattern: 'return', minimum: 2 }, result).held).toBe(false);
  });

  it('treats an absent file as unable to satisfy a positive predicate and unable to violate a negative one', () => {
    const result = unchanged();
    expect(evaluatePredicate({ kind: 'containsPhrase', path: 'gone', phrase: 'x' }, result).held).toBe(false);
    expect(evaluatePredicate({ kind: 'lacksPhrase', path: 'gone', phrase: 'x' }, result).held).toBe(true);
  });

  it('reports an uncompilable fixture pattern as a fixture defect rather than throwing mid-campaign', () => {
    const verdict = evaluatePredicate({ kind: 'matches', path: 'b.js', pattern: '([' }, unchanged());
    expect(verdict.held).toBe(false);
    expect(verdict.detail).toMatch(/fixture defect/);
  });

  it('reads JSON by pointer, including array indices and escapes', () => {
    const document = JSON.parse(baseline.get('a.json')!);
    expect(resolveJSONPointer(document, '')).toEqual(document);
    expect(resolveJSONPointer(document, '/fields/0')).toBe('amount');
    expect(resolveJSONPointer(document, '/nested/deep/1')).toBe(2);
    expect(resolveJSONPointer(document, '/fields/9')).toBeUndefined();
    expect(resolveJSONPointer(document, '/missing')).toBeUndefined();
    expect(resolveJSONPointer(document, 'fields')).toBeUndefined();
    expect(resolveJSONPointer({ 'a/b': 1, 'c~d': 2 }, '/a~1b')).toBe(1);
    expect(resolveJSONPointer({ 'a/b': 1, 'c~d': 2 }, '/c~0d')).toBe(2);
  });

  it('decides the JSON predicates, and says so when the file does not parse', () => {
    const result = unchanged();
    expect(evaluatePredicate({ kind: 'parsesAsJSON', path: 'a.json' }, result).held).toBe(true);
    expect(evaluatePredicate({ kind: 'parsesAsJSON', path: 'b.js' }, result).held).toBe(false);
    expect(evaluatePredicate({ kind: 'jsonEquals', path: 'a.json', pointer: '/fields', value: ['amount', 'region'] }, result).held).toBe(true);
    expect(evaluatePredicate({ kind: 'jsonEquals', path: 'a.json', pointer: '/fields', value: ['region', 'amount'] }, result).held).toBe(false);
    expect(evaluatePredicate({ kind: 'jsonContains', path: 'a.json', pointer: '/fields', value: 'region' }, result).held).toBe(true);
    expect(evaluatePredicate({ kind: 'jsonContains', path: 'a.json', pointer: '/fields', value: 'currency' }, result).held).toBe(false);
    expect(evaluatePredicate({ kind: 'jsonExcludes', path: 'a.json', pointer: '/fields', value: 'currency' }, result).held).toBe(true);
    expect(evaluatePredicate({ kind: 'jsonExcludes', path: 'a.json', pointer: '/fields', value: 'region' }, result).held).toBe(false);
    expect(evaluatePredicate({ kind: 'jsonHasPointer', path: 'a.json', pointer: '/nested' }, result).held).toBe(true);
    expect(evaluatePredicate({ kind: 'jsonLacksPointer', path: 'a.json', pointer: '/nope' }, result).held).toBe(true);

    const broken = evaluatePredicate({ kind: 'jsonEquals', path: 'b.js', pointer: '/x', value: 1 }, result);
    expect(broken.held).toBe(false);
    expect(broken.detail).toMatch(/does not parse as JSON/);
  });

  it('compares JSON values structurally rather than by key order', () => {
    const result = context(new Map([['a.json', '{"o":{"b":2,"a":1}}']]));
    expect(evaluatePredicate({ kind: 'jsonEquals', path: 'a.json', pointer: '/o', value: { a: 1, b: 2 } }, result).held).toBe(true);
  });

  it('evaluates an assertion set in a stable order and preserves every label', () => {
    const assertions: DevelopmentAssertion[] = [
      { id: 'z', purpose: 'p', metric: 'answerAccuracy', visibility: 'heldOut', predicate: { kind: 'fileExists', path: 'b.js' } },
      { id: 'a', purpose: 'p', metric: 'answerAccuracy', visibility: 'stated', predicate: { kind: 'fileExists', path: 'nope' }, shortcutProbe: true },
    ];
    const outcomes = evaluateAssertions(assertions, unchanged());
    expect(outcomes.map((outcome) => outcome.id)).toEqual(['a', 'z']);
    expect(outcomes[0]).toMatchObject({ held: false, shortcutProbe: true, visibility: 'stated', metric: 'answerAccuracy' });
    expect(outcomes[1]).toMatchObject({ held: true, shortcutProbe: false, visibility: 'heldOut' });
    expect(outcomes.every((outcome) => outcome.detail.length > 0)).toBe(true);
  });

  it('seals an assertion set independently of the order it was written in', () => {
    const one: DevelopmentAssertion = { id: 'one', purpose: 'p', metric: 'answerAccuracy', visibility: 'heldOut', predicate: { kind: 'fileExists', path: 'x' } };
    const two: DevelopmentAssertion = { id: 'two', purpose: 'p', metric: 'answerAccuracy', visibility: 'stated', predicate: { kind: 'fileAbsent', path: 'y' } };
    expect(assertionsDigest([one, two])).toBe(assertionsDigest([two, one]));
    expect(assertionsDigest([one])).not.toBe(assertionsDigest([one, two]));
  });
});

